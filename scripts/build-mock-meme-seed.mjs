import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const fixtureUrl = new URL('../database/seeds/internet-memes.json', import.meta.url);
const fixture = JSON.parse(readFileSync(fixtureUrl, 'utf8'));
const quote = (text) => `'${String(text).replaceAll("'", "''")}'`;
const uuid = (key) => {
  const hex = createHash('sha256').update(`${fixture.batch}:${key}`).digest('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
};
const ids = new Set();
const rows = fixture.posts.map((post, index) => {
  const template = fixture.templates[post.templateId];
  if (!template || !/^https:\/\/i\.imgflip\.com\/[a-z0-9]+\.(jpg|png|webp)$/.test(template.url)) throw new Error(`Missing verified template ${post.templateId}`);
  if (!['dry', 'absurd', 'wholesome'].includes(post.style) || post.caption.length > 280 || post.situation.length < 10 || post.situation.length > 500) throw new Error('Invalid mock post');
  const id = uuid(`${post.topic}:${post.style}`);
  if (ids.has(id)) throw new Error('Duplicate topic/style');
  ids.add(id);
  const provenance = JSON.stringify({ kind: 'mock', batch: fixture.batch, topic: post.topic, template, source: fixture.source });
  return `  (${[id, fixture.ownerId, post.situation, provenance, post.caption, post.style, fixture.batch, template.url].map(quote).join(', ')}, now() - interval '${index * 8} hours')`;
});
const sql = `-- Generated by scripts/build-mock-meme-seed.mjs. Batch: ${fixture.batch}
-- Target project: ${fixture.projectRef}. Existing rows are never updated.
begin;
do $seed$
begin
  if not exists (
    select 1 from public.profiles
    where user_id = ${quote(fixture.ownerId)}::uuid and username = ${quote(fixture.ownerUsername)} and is_superadmin = true
  ) then raise exception 'Expected mock import owner is missing; refusing to seed'; end if;
end;
$seed$;
insert into public.ai_generations (id, user_id, situation, prompt, caption, style, model, image_path, created_at)
values
${rows.join(',\n')}
on conflict (id) do nothing;
commit;
`;
writeFileSync(new URL('../database/seeds/internet-memes.sql', import.meta.url), sql);
console.log(`Prepared ${rows.length} mock memes (${ids.size} stable IDs).`);
